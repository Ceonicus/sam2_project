import torch
import gc
import os
import cv2
import numpy as np
from ultralytics import YOLO, SAM

# -----------------------------
# CONFIG (Updated for Container)
# -----------------------------
# Base directory inside your container
BASE_DIR = "/opt/sam2_project"

input_dir = os.path.join(BASE_DIR, "input_images2")
output_dir = os.path.join(BASE_DIR, "dataset2")

# Ensure these weights are located in ~/sam2_project on your desktop
yolo_weights = os.path.join(BASE_DIR, "accordwireseg3.pt")
sam_weights = os.path.join(BASE_DIR, "sam2.1_t.pt")  

device = "cuda"

# Mask filtering threshold (Minimum pixel count to be considered valid)
MIN_MASK_AREA = 1000  

# -----------------------------
# CREATE OUTPUT FOLDERS
# -----------------------------
os.makedirs(os.path.join(output_dir, "images"), exist_ok=True)
os.makedirs(os.path.join(output_dir, "masks"), exist_ok=True)
os.makedirs(os.path.join(output_dir, "masked"), exist_ok=True)

# -----------------------------
# LOAD MODELS ONCE
# -----------------------------
# Loading outside the loop prevents GPU memory thrashing on the Orin Nano
print("🚀 Loading YOLO model...")
yolo_model = YOLO(yolo_weights)

print("🚀 Loading SAM model...")
sam_model = SAM(sam_weights)

# -----------------------------
# PROCESS IMAGES
# -----------------------------
if not os.path.exists(input_dir):
    print(f"❌ Error: Input directory {input_dir} not found!")
    exit()

image_files = [f for f in os.listdir(input_dir) if f.lower().endswith((".png", ".jpg", ".jpeg"))]

print(f"📂 Found {len(image_files)} images in {input_dir}.")

for idx, img_name in enumerate(image_files):
    print(f"\n🖼️  Processing [{idx+1}/{len(image_files)}]: {img_name}")
    
    img_path = os.path.join(input_dir, img_name)

    # -----------------------------
    # STEP 1: YOLO DETECTION
    # -----------------------------
    # half=True uses FP16 precision, which is much faster on Jetson
    yolo_results = yolo_model.predict(
        img_path,
        device=device,
        half=True,
        conf=0.2,
        iou=0.2,
        imgsz=1280, 
        verbose=False
    )

    boxes = yolo_results[0].boxes.xyxy.tolist()

    if not boxes:
        print("⏭️  No detection from YOLO. Skipping.")
        continue

    # -----------------------------
    # STEP 2: SAM SEGMENTATION
    # -----------------------------
    sam_results = sam_model.predict(
        img_path,
        bboxes=boxes,
        device=device,
        half=True,
        retina_masks=False,
        verbose=False
    )

    result = sam_results[0]

    if result.masks is None:
        print("⏭️  No masks generated by SAM. Skipping.")
        continue

    # -----------------------------
    # STEP 3: COMBINE MASKS
    # -----------------------------
    # Flattening multiple detections into a single binary mask
    masks = result.masks.data.cpu().numpy()  # Shape: (N, H, W)
    combined_mask = np.any(masks, axis=0).astype(np.uint8) * 255

    # -----------------------------
    # STEP 4: FILTER BAD MASKS
    # -----------------------------
    mask_area = np.sum(combined_mask > 0)

    if mask_area < MIN_MASK_AREA:
        print(f"⚠️  Mask too small ({mask_area} px). Skipping.")
        continue

    # -----------------------------
    # STEP 5: SAVE DATASET
    # -----------------------------
    image = cv2.imread(img_path)

    if image is None:
        print("❌ Failed to read image. Skipping.")
        continue

    # Generate visual verification (masked image)
    masked_img = cv2.bitwise_and(image, image, mask=combined_mask)

    base_name = os.path.splitext(img_name)[0]

    cv2.imwrite(os.path.join(output_dir, "images", f"{base_name}.png"), image)
    cv2.imwrite(os.path.join(output_dir, "masks", f"{base_name}_mask.png"), combined_mask)
    cv2.imwrite(os.path.join(output_dir, "masked", f"{base_name}_masked.png"), masked_img)

    print(f"✅ Saved: {base_name} (Area: {mask_area} px)")

    # -----------------------------
    # ITERATION CLEANUP
    # -----------------------------
    # Clear internal references to free up VRAM for the next image
    del yolo_results
    del sam_results
    gc.collect()
    torch.cuda.empty_cache()

# -----------------------------
# FINAL CLEANUP
# -----------------------------
del yolo_model
del sam_model
gc.collect()
torch.cuda.empty_cache()

print("\n✨ Dataset generation complete. Check your 'dataset' folder!")
